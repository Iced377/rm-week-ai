export function getLanguage() { try { return localStorage.getItem(KEY) === 'en' ? 'en' : 'ar'; } catch { return 'ar'; } }
export function translate(value) {
  if (typeof value !== 'string' || getLanguage() !== 'ar') return value;
  const trimmed = value.trim();
  if (Object.prototype.hasOwnProperty.call(AR, trimmed)) return value.replace(trimmed, AR[trimmed]);
  for (const [pattern, render] of DYNAMIC) { const match=trimmed.match(pattern); if(match) return value.replace(trimmed,render(...match)); }
  // Template literals and paragraphs often combine several independently-authored phrases.
  // Translate the longest known phrases within those strings, with word boundaries for
  // English words so short entries cannot corrupt unrelated text.
  const entries = Object.entries(AR).filter(([k]) => k.trim().length >= 4).sort((a,b) => b[0].length-a[0].length);
  const escape = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const pattern = entries.map(([source]) => ( /^[A-Za-z0-9]/.test(source) ? '(?<![A-Za-z0-9])' : '' ) + escape(source) + ( /[A-Za-z0-9]$/.test(source) ? '(?![A-Za-z0-9])' : '' )).join('|');
  const replacements = new Map(entries);
  return value.replace(new RegExp(pattern, 'g'), match => replacements.get(match) ?? match);
}
function translateAttributes(el) {
  for (const name of ['aria-label','title','placeholder','alt']) {
    const val = el.getAttribute?.(name);
    if (val) { const next = translate(val); if (next !== val) el.setAttribute(name, next); }
  }
}
export function translateTree(root) {
  if (getLanguage() !== 'ar' || !root) return;
  const doc = root.ownerDocument || document;
  const walker = doc.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes=[]; while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(n => { if (n.parentElement?.closest('[data-noi18n]')) return; const next=translate(n.nodeValue); if (next !== n.nodeValue) n.nodeValue=next; });
  if (root.nodeType === Node.ELEMENT_NODE) { translateAttributes(root); root.querySelectorAll?.('*').forEach(translateAttributes); }
}
